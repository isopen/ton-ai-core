const M4 = new Uint8Array(256);
const M5 = new Uint8Array(256);
{
  for (let i = 0; i < 256; i++) {
    let a = i;
    let a2 = (a << 1) ^ (a & 0x80 ? 0x1b : 0); a2 &= 0xff;
    M0[i] = a2;
    M1[i] = a2 ^ a;
  }
  M2[0] = 0; M3[0] = 0; M4[0] = 0; M5[0] = 0;
  for (let i = 1; i < 256; i++) {
    const a4 = M0[M0[i]];
    const a8 = M0[a4];
    M2[i] = a8 ^ i;
    M3[i] = a8 ^ M0[i] ^ i;
    M4[i] = a8 ^ a4 ^ i;
    M5[i] = a8 ^ a4 ^ M0[i];
  }
}

const rcon = new Uint8Array([0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]);

export class AES256ECB {
  static readonly sBox = S;
  static readonly invSBox = Si;

  private key: Buffer;
  private useNative: boolean;
  private roundKeys: Buffer[] = [];

  private nativeEnc: any = null;
  private nativeDec: any = null;

  constructor(key: Uint8Array) {
    if (!key) throw new Error('Key must not be null or undefined');
    if (key.length !== 32) throw new Error('AES-256 requires a 32-byte key');
    this.key = Buffer.from(key);
    this.useNative = isNode();
    if (!this.useNative) {
      this.keyExpansion(this.key);
    }
  }

  destroy(): void {
    for (const ctx of [this.nativeEnc, this.nativeDec]) {
      if (ctx) {
        try { ctx.final(); } catch {}
      }
    }
    this.nativeEnc = null;
    this.nativeDec = null;
    this.key.fill(0);
    for (const rk of this.roundKeys) rk.fill(0);
    this.roundKeys = [];
  }

  private getNativeEnc(): any {
    if (!this.nativeEnc) {
      const crypto = require('crypto');
      this.nativeEnc = crypto.createCipheriv('aes-256-ecb', this.key, null);
      this.nativeEnc.setAutoPadding(false);
    }
    return this.nativeEnc;
  }

  private getNativeDec(): any {
    if (!this.nativeDec) {
      const crypto = require('crypto');
      this.nativeDec = crypto.createDecipheriv('aes-256-ecb', this.key, null);
      this.nativeDec.setAutoPadding(false);
    }
    return this.nativeDec;
  }

  private keyExpansion(key: Buffer): void {
    const Nk = 8, Nr = 14;
    const w = Buffer.alloc(4 * (Nr + 1) * 4);
    key.copy(w, 0, 0, 32);
    for (let i = 8; i < 4 * (Nr + 1); i++) {
      const temp = Buffer.alloc(4);
      temp[0] = w[4*(i-1)]; temp[1] = w[4*(i-1)+1]; temp[2] = w[4*(i-1)+2]; temp[3] = w[4*(i-1)+3];
      if (i % Nk === 0) {
        const t = temp[0]; temp[0] = temp[1]; temp[1] = temp[2]; temp[2] = temp[3]; temp[3] = t;
        for (let j = 0; j < 4; j++) temp[j] = S[temp[j]];
        temp[0] ^= rcon[Math.floor(i / Nk)];
        for (let t2 = 0; t2 < 4; t2++) w[4*i + t2] = w[4*(i - Nk) + t2] ^ temp[t2];
      } else if (Nk > 6 && i % Nk === 4) {
        for (let j = 0; j < 4; j++) temp[j] = S[temp[j]];
        for (let t2 = 0; t2 < 4; t2++) w[4*i + t2] = w[4*(i - Nk) + t2] ^ temp[t2];
      } else {
        for (let t2 = 0; t2 < 4; t2++) w[4*i + t2] = w[4*(i - Nk) + t2] ^ temp[t2];
      }
    }
    this.roundKeys = [];
    for (let i = 0; i < Nr + 1; i++) {
      this.roundKeys.push(Buffer.from(w.subarray(i * 16, (i + 1) * 16)));
    }
  }

  encryptBlock(block: Uint8Array): Buffer {
    if (!block) throw new Error('Block must not be null or undefined');
    if (block.length !== 16) throw new Error('Block must be 16 bytes');
    if (this.useNative) {
      return Buffer.from(this.getNativeEnc().update(block));
    }
    const s = Buffer.from(block);
    let i: number;

    xorKey(s, this.roundKeys[0]);

    for (let round = 1; round < 14; round++) {
      const rk = this.roundKeys[round];
      for (i = 0; i < 16; i++) s[i] = S[s[i]];
      shiftRows(s);
      mixColumns(s);
      xorKey(s, rk);
    }

    for (i = 0; i < 16; i++) s[i] = S[s[i]];
    shiftRows(s);
    xorKey(s, this.roundKeys[14]);
    return s;
  }

  decryptBlock(block: Uint8Array): Buffer {
    if (!block) throw new Error('Block must not be null or undefined');
    if (block.length !== 16) throw new Error('Block must be 16 bytes');
    if (this.useNative) {
      return Buffer.from(this.getNativeDec().update(block));
    }
    const s = Buffer.from(block);
    let i: number;

    xorKey(s, this.roundKeys[14]);

    for (let round = 13; round >= 1; round--) {
      invShiftRows(s);
      for (i = 0; i < 16; i++) s[i] = Si[s[i]];
      xorKey(s, this.roundKeys[round]);
      invMixColumns(s);
    }

    invShiftRows(s);
    for (i = 0; i < 16; i++) s[i] = Si[s[i]];
    xorKey(s, this.roundKeys[0]);
    return s;
  }

  decryptBlockInPlace(s: Buffer): Buffer {
    let i: number;
    xorKey(s, this.roundKeys[14]);
    for (let round = 13; round >= 1; round--) {
      invShiftRows(s);
      for (i = 0; i < 16; i++) s[i] = Si[s[i]];
      xorKey(s, this.roundKeys[round]);
      invMixColumns(s);
    }
    invShiftRows(s);
    for (i = 0; i < 16; i++) s[i] = Si[s[i]];
    xorKey(s, this.roundKeys[0]);
    return s;
  }
}

function xorKey(s: Buffer, rk: Buffer): void {
  for (let i = 0; i < 16; i++) s[i] ^= rk[i];
}

function shiftRows(s: Buffer): void {
  let t = s[1]; s[1] = s[5]; s[5] = s[9]; s[9] = s[13]; s[13] = t;
  t = s[2]; s[2] = s[10]; s[10] = t;
  t = s[6]; s[6] = s[14]; s[14] = t;
  t = s[3]; s[3] = s[15]; s[15] = s[11]; s[11] = s[7]; s[7] = t;
}

function invShiftRows(s: Buffer): void {
  let t = s[13]; s[13] = s[9]; s[9] = s[5]; s[5] = s[1]; s[1] = t;
  t = s[10]; s[10] = s[2]; s[2] = t;
  t = s[14]; s[14] = s[6]; s[6] = t;
  t = s[7]; s[7] = s[11]; s[11] = s[15]; s[15] = s[3]; s[3] = t;
}

function mixColumns(s: Buffer): void {
  for (let c = 0; c < 4; c++) {
    const i = c * 4;
    const a0 = s[i], a1 = s[i+1], a2 = s[i+2], a3 = s[i+3];
    s[i]   = M0[a0] ^ M1[a1] ^ a2 ^ a3;
    s[i+1] = a0 ^ M0[a1] ^ M1[a2] ^ a3;
    s[i+2] = a0 ^ a1 ^ M0[a2] ^ M1[a3];
    s[i+3] = M1[a0] ^ a1 ^ a2 ^ M0[a3];
  }
}

function invMixColumns(s: Buffer): void {
  for (let c = 0; c < 4; c++) {
    const i = c * 4;
    const a0 = s[i], a1 = s[i+1], a2 = s[i+2], a3 = s[i+3];
    s[i]   = M5[a0] ^ M3[a1] ^ M4[a2] ^ M2[a3];
    s[i+1] = M2[a0] ^ M5[a1] ^ M3[a2] ^ M4[a3];
    s[i+2] = M4[a0] ^ M2[a1] ^ M5[a2] ^ M3[a3];
    s[i+3] = M3[a0] ^ M4[a1] ^ M2[a2] ^ M5[a3];
  }
}

export interface ObfuscationCipher {
    encryptBlock(block: Uint8Array | Buffer): Buffer;
    destroy(): void;
}

export function createObfuscationCipher(key: Buffer): ObfuscationCipher {
    if (key.length !== 32) throw new Error(`Obfuscation cipher key must be 32 bytes, got ${key.length}`);
    const inst = new AES256ECB(key);
    return {
        encryptBlock: (block) => inst.encryptBlock(Buffer.from(block)),
        destroy: () => inst.destroy(),
    };
}
